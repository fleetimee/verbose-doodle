  const GAP = 1;
  function glyph(ch) { return glyphs[ch] || glyphs['?']; }
  function measure(str) {
    let w = 0, max = 0;
    for (const ch of str) {
      if (ch === '\n') { max = Math.max(max, w - GAP); w = 0; continue; }
      w += glyph(ch).w + GAP;
    }
    return Math.max(max, w - GAP);
  }
  // draw text; opts: shadow color, x-scale
  function draw(surf, str, x, y, color, shadow) {
    let cx = x | 0, cy = y | 0;
    for (const ch of str) {
      if (ch === '\n') { cx = x | 0; cy += 14; continue; }
      const g = glyph(ch), p = g.px;
      if (shadow !== undefined && shadow !== null) {
        for (let i = 0; i < p.length; i += 2) {
          surf.pset(cx + p[i] + 1, cy + p[i + 1], shadow);
          surf.pset(cx + p[i], cy + p[i + 1] + 1, shadow);
          surf.pset(cx + p[i] + 1, cy + p[i + 1] + 1, shadow);
        }
      }
      for (let i = 0; i < p.length; i += 2) surf.pset(cx + p[i], cy + p[i + 1], color);
      cx += g.w + GAP;
    }
    return cx;
  }
  // Outlined text (for titles over busy backgrounds)
  function drawOutlined(surf, str, x, y, color, outline) {
    for (let oy = -1; oy <= 1; oy++) for (let ox = -1; ox <= 1; ox++) if (ox || oy) draw(surf, str, x + ox, y + oy, outline);
    draw(surf, str, x, y, color);
  }
  function wrap(str, maxW) {
    const out = [];
    for (const para of String(str).split('\n')) {
      const words = para.split(' ');
      let line = '';
      for (const wd of words) {
        const t = line ? line + ' ' + wd : wd;
        if (measure(t) > maxW && line) { out.push(line); line = wd; } else line = t;
      }
      out.push(line);
    }
    return out;
  }

